#ifndef POKEPLATINUM_CONSTANTS_FIELD_FIELD_MOVE_HELPER_H
#define POKEPLATINUM_CONSTANTS_FIELD_FIELD_MOVE_HELPER_H

// Sour Platinum: the Poketch field moves app doesn't use a party Pokemon. It passes a slot code instead (base + field
// move, see FieldMoves_GetPokemonBySlot), and the Pokemon that is shown for the move is a fixed species.
#define FIELD_MOVE_HELPER_SLOT_BASE        0x40
#define FIELD_MOVE_HELPER_SLOT_CUT         (FIELD_MOVE_HELPER_SLOT_BASE + 0)
#define FIELD_MOVE_HELPER_SLOT_FLY         (FIELD_MOVE_HELPER_SLOT_BASE + 1)
#define FIELD_MOVE_HELPER_SLOT_SURF        (FIELD_MOVE_HELPER_SLOT_BASE + 2)
#define FIELD_MOVE_HELPER_SLOT_STRENGTH    (FIELD_MOVE_HELPER_SLOT_BASE + 3)
#define FIELD_MOVE_HELPER_SLOT_DEFOG       (FIELD_MOVE_HELPER_SLOT_BASE + 4)
#define FIELD_MOVE_HELPER_SLOT_ROCK_SMASH  (FIELD_MOVE_HELPER_SLOT_BASE + 5)
#define FIELD_MOVE_HELPER_SLOT_WATERFALL   (FIELD_MOVE_HELPER_SLOT_BASE + 6)
#define FIELD_MOVE_HELPER_SLOT_ROCK_CLIMB  (FIELD_MOVE_HELPER_SLOT_BASE + 7)

#endif // POKEPLATINUM_CONSTANTS_FIELD_FIELD_MOVE_HELPER_H
